CREATE TABLE Members (
    MemberId INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Rut VARCHAR(12) NOT NULL UNIQUE,
    Name VARCHAR(100) NOT NULL,
    Phone VARCHAR(20) NOT NULL,
    Email VARCHAR(100) NULL,
    RegisteredAt TIMESTAMP DEFAULT NOW(),
    IsActive BOOLEAN DEFAULT TRUE
);

CREATE TABLE Plans (
    PlanId INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    Name VARCHAR(50) NOT NULL,
    DurationInDays INT NOT NULL,
    Price INT NOT NULL,
    IsActive BOOLEAN DEFAULT TRUE
);

CREATE TABLE Memberships (
    MembershipId INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MemberId INT NOT NULL REFERENCES Members(MemberId),
    PlanId INT NOT NULL REFERENCES Plans(PlanId),
    StartDate DATE NOT NULL,
    EndDate DATE NOT NULL,
    Status VARCHAR(20) DEFAULT 'VIGENTE' CHECK (Status IN ('VIGENTE', 'VENCIDA', 'CANCELADA'))
);

CREATE TABLE Payments (
    PaymentId INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MembershipId INT NOT NULL REFERENCES Memberships(MembershipId),
    Amount INT NOT NULL,
    PaymentDate TIMESTAMP DEFAULT NOW(),
    PaymentMethod VARCHAR(30) NOT NULL
);

CREATE TABLE Attendance (
    AttendanceId INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    MemberId INT NOT NULL REFERENCES Members(MemberId),
    EntranceDateTime TIMESTAMP DEFAULT NOW()
);